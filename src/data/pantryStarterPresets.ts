export function buildInventoryItemFromPreset(
  preset: PantryStarterPreset,
  defaultStoreId: string
): InventoryItem {
  const nowIso = new Date().toISOString();
  return {
    id: `item-starter-${preset.key}-${Date.now().toString(36)}`,
    name: preset.name,
    alias: preset.alias,
    category: preset.category,
    zone: preset.zone,
    trackingMode: preset.trackingMode,
    continuousStyle: preset.continuousStyle,
    containerSize: preset.containerSize,
    containerUnit: preset.containerUnit,
    totalPortions: preset.totalPortions,
    remainingPortions: preset.totalPortions,
    portionLabel: preset.portionLabel,
    packDescription: preset.packDescription,
    proteinPerPortion: preset.proteinPerPortion,
    defaultStoreId,
    storePurchaseCounts: { [defaultStoreId]: 1 },
    avgDaysPerFullPack: preset.avgDaysPerFullPack,
    cycleCount: 0,
    lastRestockedAt: nowIso,
    updatedAt: nowIso,
    autoAddOnEmpty: true,
  };
}
